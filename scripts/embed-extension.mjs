// Regenerates src/dynamic-tools/embedded-extension-source.ts from
// extension/bb-tools-extension.ts. Run after editing the extension:
//
//   node scripts/embed-extension.mjs
//
// The bb.host artifact is a single digest-verified file — the daemon's
// artifact cache carries only host.mjs — so the companion extension's source
// travels inside the bundle and is materialized to a scratch file at runtime
// (see companionExtensionPath in src/dynamic-tools/registry.ts). The checked-in
// copy is kept honest by embedded-extension.test.ts.
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(
  new URL("../extension/bb-tools-extension.ts", import.meta.url),
  "utf8",
);

const banner = `// Generated by scripts/embed-extension.mjs from extension/bb-tools-extension.ts — do not edit.
// Regenerate with: node scripts/embed-extension.mjs
// Embedded because the bb.host artifact ships as one file and the daemon's
// artifact cache cannot carry a sibling (bbpa-9ah); sync is guarded by
// embedded-extension.test.ts.
`;

writeFileSync(
  new URL("../src/dynamic-tools/embedded-extension-source.ts", import.meta.url),
  `${banner}export const BB_TOOLS_EXTENSION_SOURCE = ${JSON.stringify(source)};\n`,
);

console.log("embedded-extension-source.ts regenerated");
